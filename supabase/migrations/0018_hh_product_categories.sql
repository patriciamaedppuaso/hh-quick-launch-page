-- hh_product_categories: join table linking catalog products to categories
-- (a product can sit in several, e.g. a wound-care item that is also
-- urological). Depends on 0016 (hh_categories.slug).
--
-- product_id has no foreign key: the products table isn't in this project.
-- Add one later if hh_products is ever brought over.

create table hh_product_categories (
  product_id text not null,
  category_slug text not null references hh_categories(slug) on update cascade on delete cascade,
  primary key (product_id, category_slug)
);
create index hh_product_categories_category_slug_idx on hh_product_categories(category_slug);

alter table hh_product_categories enable row level security;
create policy "authenticated full access" on hh_product_categories
  for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

